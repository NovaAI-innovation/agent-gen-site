// Generate src/styles/tokens.css from tokens/tokens.json (Design Lead's DTCG tokens).
import {readFileSync, writeFileSync} from 'node:fs'
const t = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'))
const v = (o) => o.$value
const colorVars = (mode) => Object.entries(t.color[mode]).map(([k, o]) => `  --color-${k}: ${v(o)};`).join('\n')
const fam = (k) => v(t.font.family[k]).map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ')
const lines = []
lines.push('/* GENERATED by scripts/tokens.mjs from tokens/tokens.json. Do not edit by hand. */')
lines.push(':root {')
lines.push(colorVars('light'))
lines.push('  color-scheme: light;')
lines.push(`  --font-display: ${fam('display')};`)
lines.push(`  --font-body: ${fam('body')};`)
lines.push(`  --font-mono: ${fam('mono')};`)
for (const [k, o] of Object.entries(t.font.weight)) lines.push(`  --weight-${k}: ${v(o)};`)
for (const [k, o] of Object.entries(t.typography)) {
  if (k.startsWith('$')) continue
  const val = v(o)
  let size = val.fontSize
  if (k === '5xl') size = 'clamp(2.441rem, 1.8rem + 3vw, 3.052rem)'
  if (k === '4xl') size = 'clamp(1.953rem, 1.5rem + 2vw, 2.441rem)'
  lines.push(`  --text-${k}: ${size};`, `  --leading-${k}: ${val.lineHeight};`, `  --tracking-${k}: ${val.letterSpacing};`)
}
for (const [k, o] of Object.entries(t.space)) lines.push(`  --space-${k}: ${v(o)};`)
for (const [k, o] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v(o)};`)
for (const [k, o] of Object.entries(t.shadow)) {
  if (k.startsWith('$')) continue
  const s = v(o); lines.push(`  --shadow-${k}: ${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color};`)
}
lines.push(`  --measure: ${v(t.size.content.prose)};`, `  --content-wide: ${v(t.size.content.wide)};`, `  --content-max: ${v(t.size.content.max)};`, `  --target-min: ${v(t.size.target.min)};`)
for (const [k, o] of Object.entries(t.motion.duration)) lines.push(`  --duration-${k}: ${v(o)};`)
for (const [k, o] of Object.entries(t.motion.easing)) lines.push(`  --ease-${k}: cubic-bezier(${v(o).join(', ')});`)
lines.push('}')
const dark = `${colorVars('dark')}\n  color-scheme: dark;\n  --shadow-sm: 0 1px 2px 0 #00000066;\n  --shadow-md: none;\n  --shadow-lg: none;`
lines.push(`:root[data-theme="dark"] {\n${dark}\n}`)
lines.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${dark.replace(/^/gm, '  ')}\n  }\n}`)
lines.push(`@media (prefers-reduced-motion: reduce) {\n  :root { --duration-base: 0ms; --duration-slow: 0ms; }\n}`)
writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), lines.join('\n') + '\n')
console.log('tokens.css written')
